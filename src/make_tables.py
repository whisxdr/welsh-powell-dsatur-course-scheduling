"""Generate LaTeX table fragments and a key-numbers digest from the results.

Every number that appears in the manuscript tables is produced here from the
frozen artefacts; nothing is typed by hand.  Run after the benchmark, the
optimality study, the graph audit and the real case study:

    python src/make_tables.py
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

SIZES = (20, 40, 60, 80, 100)
PROBABILITIES = (0.1, 0.3, 0.5, 0.7)
SCENARIOS = ("small_program", "medium_program", "large_program")
SCENARIO_LABEL = {
    "small_program": "program kecil",
    "medium_program": "program menengah",
    "large_program": "program besar",
}


def fmt_p(value: float) -> str:
    if value >= 0.001:
        return f"{value:.3f}"
    exponent = int(f"{value:e}".split("e")[1])
    mantissa = value / 10**exponent
    return f"${mantissa:.1f}\\times10^{{{exponent}}}$"


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def table_colors(frame: pd.DataFrame) -> str:
    experiment_a = frame[frame["experiment"] == "A"]
    lines = [
        "% generated by src/make_tables.py -- do not edit",
        "\\begin{table}[!t]",
        "\\centering",
        "\\caption{Rata-rata jumlah warna (slot waktu) pada Eksperimen~A, 30 instans "
        "per sel. Setiap sel berisi Welsh--Powell / DSATUR.}",
        "\\label{tab:colors}",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular}{@{}lcccc@{}}",
        "\\toprule",
        "$|V|$ & $p=0.1$ & $p=0.3$ & $p=0.5$ & $p=0.7$ \\\\",
        "\\midrule",
    ]
    for n in SIZES:
        cells = []
        for p in PROBABILITIES:
            subset = experiment_a[(experiment_a["n"] == n) & (experiment_a["p"] == p)]
            cells.append(f"{subset['wp_colors'].mean():.2f} / {subset['ds_colors'].mean():.2f}")
        lines.append(f"{n} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)


def table_runtime(frame: pd.DataFrame) -> str:
    experiment_a = frame[frame["experiment"] == "A"]
    lines = [
        "% generated by src/make_tables.py -- do not edit",
        "\\begin{table}[!t]",
        "\\centering",
        "\\caption{Waktu eksekusi median (ms) pada Eksperimen~A, 30 instans per sel, "
        "dari median tujuh pengukuran berulang per instans. Setiap sel berisi "
        "Welsh--Powell / DSATUR.}",
        "\\label{tab:runtime}",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular}{@{}lcccc@{}}",
        "\\toprule",
        "$|V|$ & $p=0.1$ & $p=0.3$ & $p=0.5$ & $p=0.7$ \\\\",
        "\\midrule",
    ]
    for n in SIZES:
        cells = []
        for p in PROBABILITIES:
            subset = experiment_a[(experiment_a["n"] == n) & (experiment_a["p"] == p)]
            wp = 1000.0 * subset["wp_time_median_s"].median()
            ds = 1000.0 * subset["ds_time_median_s"].median()
            cells.append(f"{wp:.3f} / {ds:.3f}")
        lines.append(f"{n} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)


def table_win_tie_loss(frame: pd.DataFrame) -> str:
    experiment_a = frame[frame["experiment"] == "A"]
    experiment_b = frame[frame["experiment"] == "B"]
    lines = [
        "% generated by src/make_tables.py -- do not edit",
        "\\begin{table}[!t]",
        "\\centering",
        "\\caption{Jumlah kemenangan, seri, dan kekalahan. Menang berarti memakai warna "
        "lebih sedikit daripada heuristik lain pada instans yang sama.}",
        "\\label{tab:wtl}",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular}{@{}lcccc@{}}",
        "\\toprule",
        "Blok & $n$ & WP & Seri & DSATUR \\\\",
        "\\midrule",
    ]
    for p in PROBABILITIES:
        subset = experiment_a[experiment_a["p"] == p]
        lines.append(
            f"A, $p={p:.1f}$ & {len(subset)} & "
            f"{(subset['winner'] == 'welsh_powell').sum()} & "
            f"{(subset['winner'] == 'tie').sum()} & "
            f"{(subset['winner'] == 'dsatur').sum()} \\\\"
        )
    lines.append("\\midrule")
    for scenario in SCENARIOS:
        subset = experiment_b[experiment_b["scenario"] == scenario]
        lines.append(
            f"B, {SCENARIO_LABEL[scenario].replace('program ', '')} & {len(subset)} & "
            f"{(subset['winner'] == 'welsh_powell').sum()} & "
            f"{(subset['winner'] == 'tie').sum()} & "
            f"{(subset['winner'] == 'dsatur').sum()} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)


def table_statistics(stats: dict) -> str:
    rows: list[tuple[str, dict, bool]] = [("Semua", stats["overall"], True)]
    for p in PROBABILITIES:
        rows.append((f"A, $p={p:.1f}$", stats["by_probability"][f"{p:.1f}"], False))
    for scenario in SCENARIOS:
        rows.append(
            (
                f"B, {SCENARIO_LABEL[scenario].replace('program ', '')}",
                stats["by_scenario"][scenario],
                False,
            )
        )

    lines = [
        "% generated by src/make_tables.py -- do not edit",
        "\\begin{table}[!t]",
        "\\centering",
        "\\caption{Perbandingan berpasangan jumlah warna. $\\Delta k$ adalah rata-rata "
        "$k_{\\mathrm{DSATUR}}-k_{\\mathrm{WP}}$; $r$ adalah korelasi peringkat-biserial; "
        "$p$ adalah nilai-$p$ Wilcoxon dua sisi; $p_{\\mathrm{Holm}}$ adalah nilai yang "
        "disesuaikan dalam keluarga subkelompok.}",
        "\\label{tab:stats}",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{@{}lrrrrr@{}}",
        "\\toprule",
        "Blok & $\\Delta k$ & $R_k$ & $r$ & $p$ & $p_{\\mathrm{Holm}}$ \\\\",
        "\\midrule",
    ]
    for label, block, primary in rows:
        holm = "--" if primary else fmt_p(block["colors_wilcoxon"]["holm_adjusted_p"])
        lines.append(
            f"{label} & {block['mean_color_difference_ds_minus_wp']:+.3f} & "
            f"{block['mean_reduction_pct']:.2f} & "
            f"{block['colors_wilcoxon']['rank_biserial']:+.3f} & "
            f"{fmt_p(block['colors_wilcoxon']['p_value'])} & {holm} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)


def table_dataset(audit: pd.DataFrame, real: dict) -> str:
    experiment_a = audit[audit["experiment"] == "A"]
    experiment_b = audit[audit["experiment"] == "B"]
    real_dataset = real["dataset"]
    real_structure = real["structure"]
    lines = [
        "% generated by src/make_tables.py -- do not edit",
        "\\begin{table}[!t]",
        "\\centering",
        "\\caption{Komposisi dan struktur himpunan data. $d(G)$ adalah kepadatan "
        "teramati, $\\bar{C}$ koefisien klaster rata-rata.}",
        "\\label{tab:dataset}",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular}{@{}lrrrrr@{}}",
        "\\toprule",
        "Blok & $n$ & $|V|$ & $|E|$ & $d(G)$ & $\\bar{C}$ \\\\",
        "\\midrule",
        f"A (acak) & {len(experiment_a)} & 20--100 & "
        f"{int(experiment_a['m'].min())}--{int(experiment_a['m'].max())} & "
        f"{experiment_a['density'].min():.3f}--{experiment_a['density'].max():.3f} & "
        f"{experiment_a['avg_clustering'].mean():.3f} \\\\",
    ]
    for scenario in SCENARIOS:
        subset = experiment_b[experiment_b["block"] == scenario]
        lines.append(
            f"B, {SCENARIO_LABEL[scenario].replace('program ', '')} & {len(subset)} & "
            f"{int(subset['n'].iloc[0])} & "
            f"{int(subset['m'].min())}--{int(subset['m'].max())} & "
            f"{subset['density'].min():.3f}--{subset['density'].max():.3f} & "
            f"{subset['avg_clustering'].mean():.3f} \\\\"
        )
    lines.append(
        f"C (nyata) & 1 & {real_dataset['n_courses']} & {real_dataset['n_edges']} & "
        f"{real_dataset['density']:.3f} & {real_structure['avg_clustering']:.3f} \\\\"
    )
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)


def table_optimality(optimality: dict) -> str:
    """Compact matrix: rows are sizes/scenarios, columns are edge probabilities."""
    blocks = optimality["by_block"]
    lookup = {(row["experiment"], row["block"]): row for row in blocks}

    def parse_block(block: str) -> tuple[int, float]:
        size, probability = block.split("_p")
        return int(size[1:]), float(probability)

    a_blocks = [parse_block(row["block"]) for row in blocks if row["experiment"] == "A"]
    sizes = sorted({n for n, _ in a_blocks})
    probabilities = sorted({p for _, p in a_blocks})

    def cell(n: int, p: float) -> str:
        row = lookup.get(("A", f"n{n}_p{p:.1f}"))
        if row is None:
            return "--"
        return f"{row['mean_gap_wp']:.2f}/{row['mean_gap_ds']:.2f}"

    lines = [
        "% generated by src/make_tables.py -- do not edit",
        "\\begin{table}[!t]",
        "\\centering",
        "\\caption{Celah optimalitas menurut \\eqref{eq:gap} pada instans yang "
        "$\\chi(G)$-nya terbukti. Setiap sel berisi $G_{\\mathrm{WP}}/G_{\\mathrm{DS}}$ "
        "dalam persen; tanda -- berarti sel itu di luar cakupan eksak.}",
        "\\label{tab:optimality}",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{@{}lcccc@{}}",
        "\\toprule",
        " & $p=0.1$ & $p=0.3$ & $p=0.5$ & $p=0.7$ \\\\",
        "\\midrule",
        "\\multicolumn{5}{@{}l}{\\emph{Eksperimen A (acak)}} \\\\",
    ]
    for n in sizes:
        cells = " & ".join(cell(n, p) for p in probabilities)
        lines.append(f"$|V|={n}$ & {cells} \\\\")
    lines.append("\\midrule")
    lines.append("\\multicolumn{5}{@{}l}{\\emph{Eksperimen B (pendaftaran)}} \\\\")
    for scenario in SCENARIOS:
        row = lookup.get(("B", scenario))
        if row is None:
            continue
        label = SCENARIO_LABEL[scenario].replace("program ", "")
        lines.append(
            f"{label} & \\multicolumn{{4}}{{c}}"
            f"{{{row['mean_gap_wp']:.2f}/{row['mean_gap_ds']:.2f}}} \\\\"
        )
    overall = optimality["overall"]
    lines.append("\\midrule")
    lines.append(
        f"Total & \\multicolumn{{4}}{{c}}"
        f"{{{overall['mean_gap_wp_pct']:.2f}/{overall['mean_gap_ds_pct']:.2f}}} \\\\"
    )
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)


def key_numbers(
    frame: pd.DataFrame,
    stats: dict,
    optimality: dict,
    real: dict,
    audit: pd.DataFrame,
) -> dict[str, object]:
    experiment_a = frame[frame["experiment"] == "A"]
    experiment_b = frame[frame["experiment"] == "B"]
    overall = stats["overall"]
    opt = optimality["overall"]
    audit_a = audit[audit["experiment"] == "A"]
    audit_b = audit[audit["experiment"] == "B"]
    return {
        "instances_total": int(len(frame)),
        "instances_experiment_a": int(len(experiment_a)),
        "instances_experiment_b": int(len(experiment_b)),
        "algorithm_instance_comparisons": int(2 * len(frame)),
        "overall_wp_mean_colors": round(overall["wp_mean_colors"], 4),
        "overall_ds_mean_colors": round(overall["ds_mean_colors"], 4),
        "overall_mean_reduction_pct": round(overall["mean_reduction_pct"], 4),
        "overall_dsatur_wins": overall["dsatur_wins"],
        "overall_ties": overall["ties"],
        "overall_wp_wins": overall["wp_wins"],
        "overall_runtime_ratio": round(overall["runtime_ratio_ds_over_wp"], 4),
        "overall_colors_p": overall["colors_wilcoxon"]["p_value"],
        "overall_colors_effect": overall["colors_wilcoxon"]["rank_biserial"],
        "overall_runtime_p": overall["runtime_wilcoxon"]["p_value"],
        "overall_runtime_effect": overall["runtime_wilcoxon"]["rank_biserial"],
        "overall_color_ci": [round(v, 4) for v in overall["color_difference_bootstrap_95ci"]],
        "reduction_by_p": {
            key: round(block["mean_reduction_pct"], 4)
            for key, block in stats["by_probability"].items()
        },
        "reduction_by_n": {
            key: round(block["mean_reduction_pct"], 4) for key, block in stats["by_size"].items()
        },
        "reduction_by_scenario": {
            key: round(block["mean_reduction_pct"], 4)
            for key, block in stats["by_scenario"].items()
        },
        "p_by_scenario": {
            key: block["colors_wilcoxon"]["p_value"] for key, block in stats["by_scenario"].items()
        },
        "holm_p_by_scenario": {
            key: block["colors_wilcoxon"]["holm_adjusted_p"]
            for key, block in stats["by_scenario"].items()
        },
        "holm_p_by_probability": {
            key: block["colors_wilcoxon"]["holm_adjusted_p"]
            for key, block in stats["by_probability"].items()
        },
        "runtime_ratio_by_p": {
            key: round(block["runtime_ratio_ds_over_wp"], 4)
            for key, block in stats["by_probability"].items()
        },
        "max_wp_colors": int(frame["wp_colors"].max()),
        "max_ds_colors": int(frame["ds_colors"].max()),
        "total_conflicts": int(frame["wp_conflicts"].sum() + frame["ds_conflicts"].sum()),
        "experiment_b_ties": int((experiment_b["winner"] == "tie").sum()),
        "experiment_b_instances": int(len(experiment_b)),
        "optimality": {
            "instances_attempted": opt["instances_attempted"],
            "instances_proven": opt["instances_proven"],
            "instances_unproven": opt["instances_attempted"] - opt["instances_proven"],
            "instances_without_proof": 690 - opt["instances_proven"],
            "share_proven": opt["share_proven"],
            "share_of_benchmark": opt["share_of_benchmark"],
            "mean_gap_wp_pct": opt["mean_gap_wp_pct"],
            "mean_gap_ds_pct": opt["mean_gap_ds_pct"],
            "max_gap_wp_pct": opt["max_gap_wp_pct"],
            "max_gap_ds_pct": opt["max_gap_ds_pct"],
            "wp_optimal_share": opt["wp_optimal_share"],
            "ds_optimal_share": opt["ds_optimal_share"],
        },
        "real_case": {
            "n_courses": real["dataset"]["n_courses"],
            "n_students": real["dataset"]["n_students"],
            "n_edges": real["dataset"]["n_edges"],
            "density": real["dataset"]["density"],
            "avg_clustering": real["structure"]["avg_clustering"],
            "components": real["structure"]["components"],
            "max_degree": real["structure"]["max_degree"],
            "k_wp": real["k_wp"],
            "k_ds": real["k_ds"],
            "clique_lower_bound": real["clique_lower_bound"],
            "chromatic_number_proven": real["chromatic_number_proven"],
            "runtime_ratio": real["runtime_ratio_ds_over_wp"],
            "wp_time_median_ms": real["wp_time_median_ms"],
            "ds_time_median_ms": real["ds_time_median_ms"],
        },
        "audit": {
            "clustering_experiment_a": float(audit_a["avg_clustering"].mean()),
            "clustering_experiment_b": float(audit_b["avg_clustering"].mean()),
            "clustering_real": float(real["structure"]["avg_clustering"]),
            "components_experiment_a": float(audit_a["components"].mean()),
            "components_experiment_b": float(audit_b["components"].mean()),
        },
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, default=Path("results"))
    parser.add_argument("--tables", type=Path, default=Path("paper/tables"))
    args = parser.parse_args(argv)

    frame = pd.read_csv(args.results / "raw_results.csv")
    stats = json.loads((args.results / "statistics.json").read_text(encoding="utf-8"))
    optimality = json.loads((args.results / "optimality.json").read_text(encoding="utf-8"))
    real = json.loads((args.results / "real_case_study.json").read_text(encoding="utf-8"))
    audit = pd.read_csv(args.results / "graph_audit.csv")

    write(args.tables / "tab_colors.tex", table_colors(frame))
    write(args.tables / "tab_runtime.tex", table_runtime(frame))
    write(args.tables / "tab_wtl.tex", table_win_tie_loss(frame))
    write(args.tables / "tab_stats.tex", table_statistics(stats))
    write(args.tables / "tab_dataset.tex", table_dataset(audit, real))
    write(args.tables / "tab_optimality.tex", table_optimality(optimality))
    write(
        args.results / "key_numbers.json",
        json.dumps(key_numbers(frame, stats, optimality, real, audit), indent=2),
    )
    print(f"tables written to {args.tables}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
